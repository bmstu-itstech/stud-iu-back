from django.utils.text import slugify

SLUG_MAX_LENGTH = 128


def make_slug(title: str) -> str:
    slug = slugify(title.lower().translate(_TRANSLIT))
    return slug[:SLUG_MAX_LENGTH].rstrip("-")


